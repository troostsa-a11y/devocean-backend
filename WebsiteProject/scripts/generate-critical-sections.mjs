import { readFile, writeFile } from 'node:fs/promises';
import { LOCALES } from '../src/i18n/localeCatalog.js';

// Keep first-paint copy identical to the asynchronously loaded translations,
// without importing every complete language module into the initial bundle.
const SECTION_KEYS = [
  'menu', 'regions', 'currencies', 'nav', 'hero',
  'galleryHeading', 'location', 'contact', 'form', 'footer', 'legal',
];
const sections = {};

for (const { code } of LOCALES) {
  const { UI } = await import(new URL(`../src/i18n/langs/${code}.js`, import.meta.url));
  const selected = Object.fromEntries(SECTION_KEYS.map(key => [key, UI[key]]));
  selected.stay = { ourStory: UI.stay?.ourStory };

  for (const key of SECTION_KEYS) {
    if (!selected[key] || (typeof selected[key] === 'string' && !selected[key].trim())) {
      throw new Error(`${code}: missing critical section "${key}"`);
    }
  }
  for (const [section, keys] of [
    ['regions', ['westEu', 'eastEu', 'asia', 'americas', 'africa', 'oceania']],
    ['nav', ['home', 'stay', 'experiences', 'todo', 'gallery', 'location', 'contact', 'food']],
    ['hero', ['title', 'subtitle', 'description', 'ctaPrimary', 'ctaSecondary', 'badge', 'clickReviews', 'villageHighlights', 'goDiving']],
    ['stay', ['ourStory']],
    ['location', ['headline', 'blurb', 'viewMap']],
    ['contact', ['headline', 'blurb', 'call', 'email', 'directions', 'bookNow']],
    ['form', ['name', 'email', 'stayLabel', 'checkin', 'checkout', 'unitLabel', 'message', 'send', 'consent']],
    ['footer', ['rights', 'desc']],
  ]) {
    for (const key of keys) {
      if (typeof selected[section][key] !== 'string' || !selected[section][key].trim()) {
        throw new Error(`${code}: missing critical copy "${section}.${key}"`);
      }
    }
  }
  if (!Array.isArray(selected.location.items) || !Array.isArray(selected.form.units)) {
    throw new Error(`${code}: missing critical location/form lists`);
  }
  sections[code] = selected;
}

// One compact entry per locale keeps this generated data file focused and
// avoids duplicating the complete UI/L10N modules in the first-paint bundle.
const content = '// Generated by scripts/generate-critical-sections.mjs. Edit langs/*.js instead.\n' +
  'export const CRITICAL_SECTION_UI = {\n' +
  Object.entries(sections).map(([code, ui]) =>
    `  ${JSON.stringify(code)}: ${JSON.stringify(ui)},`
  ).join('\n') +
  '\n};\n';
const output = new URL('../src/i18n/criticalSections.generated.js', import.meta.url);

if (process.argv.includes('--check')) {
  const existing = await readFile(output, 'utf8').catch(() => null);
  if (existing !== content) {
    throw new Error('Critical section translations are stale. Run node scripts/generate-critical-sections.mjs.');
  }
  console.log(`Critical section translations match all ${LOCALES.length} locales.`);
} else {
  await writeFile(output, content, 'utf8');
  console.log(`Generated critical section translations for ${LOCALES.length} locales.`);
}
